import { build } from 'vite';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const resolve = (...parts) => path.join(projectRoot, ...parts);

// Bundle React and every component into a classic script. ES module scripts
// require an HTTP origin; this format can also run from a file:// URL.
const result = await build({
  configFile: resolve('vite.config.js'),
  publicDir: false,
  define: { 'process.env.NODE_ENV': JSON.stringify('production') },
  build: {
    outDir: resolve('dist'),
    write: false,
    minify: true,
    sourcemap: false,
    cssCodeSplit: false,
    lib: {
      entry: resolve('src/main.jsx'),
      name: 'BrandonPortfolio',
      formats: ['iife'],
      fileName: 'portfolio',
    },
  },
});

const outputs = (Array.isArray(result) ? result : [result]).flatMap((bundle) => bundle.output);
const scripts = outputs.filter((output) => output.type === 'chunk');
const styles = outputs.filter((output) => output.type === 'asset' && output.fileName.endsWith('.css'));
const otherAssets = outputs.filter((output) => output.type === 'asset' && !output.fileName.endsWith('.css'));
if (scripts.length !== 1 || !styles.length || otherAssets.length) {
  throw new Error('Standalone build requires one script and embedded assets. Add new assets to this builder before using them.');
}

const [template, theme, favicon] = await Promise.all([
  readFile(resolve('src/index.html'), 'utf8'),
  readFile(resolve('public/theme.js'), 'utf8'),
  readFile(resolve('public/favicon.svg')),
]);
const css = styles.map((style) => String(style.source)).join('\n');
const safeScript = (code) => code.replace(/<\/script/gi, '<\\/script');
const safeStyle = css.replace(/<\/style/gi, '<\\/style');
const replacements = [
  ['<link rel="icon" href="%BASE_URL%favicon.svg" type="image/svg+xml" />', `<link rel="icon" href="data:image/svg+xml;base64,${favicon.toString('base64')}" type="image/svg+xml" />`],
  ['<script src="%BASE_URL%theme.js" vite-ignore></script>', `<script>${safeScript(theme)}</script>\n    <style>${safeStyle}</style>`],
  ['<script type="module" src="/main.jsx"></script>', `<script>${safeScript(scripts[0].code)}</script>`],
];
let html = template;
for (const [marker, replacement] of replacements) {
  if (!html.includes(marker)) throw new Error(`Missing source HTML marker: ${marker}`);
  html = html.replace(marker, () => replacement);
}
html = '<!-- Generated by npm run build. Edit src/ files, then rebuild. -->\n' + html;

// Keep the last working preview if compilation fails. Only replace outputs
// after the entire app has compiled and all template markers are present.
await rm(resolve('dist'), { recursive: true, force: true });
await mkdir(resolve('dist'), { recursive: true });
await writeFile(resolve('dist/index.html'), html);
await writeFile(resolve('index.html'), html);
console.log('Built self-contained React page: index.html and dist/index.html');
console.log('Double-click index.html to view it. No npm or server is needed to open the page.');
